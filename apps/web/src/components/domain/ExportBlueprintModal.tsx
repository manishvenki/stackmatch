import React, { useState } from 'react';
import { X, Download, Printer, FileText, Code2, CheckCircle2, Loader2, Sparkles } from 'lucide-react';
import { Button } from '../ui/Button';
import { Badge } from '../ui/Badge';
import {
  Project,
  Requirement,
  Technology,
  ArchitectureNode,
  RoadmapPhase,
  ProjectBlueprint,
} from '../../types';
import { exportBlueprintToPdf } from '../../utils/pdfExport';

export interface ExportBlueprintModalProps {
  isOpen: boolean;
  onClose: () => void;
  project: Project;
  requirements: Requirement[];
  technologies: Technology[];
  architectureNodes: ArchitectureNode[];
  roadmapPhases: RoadmapPhase[];
  blueprint: ProjectBlueprint;
  onNotifySuccess?: (msg: string) => void;
}

export const ExportBlueprintModal: React.FC<ExportBlueprintModalProps> = ({
  isOpen,
  onClose,
  project,
  requirements,
  technologies,
  architectureNodes,
  roadmapPhases,
  blueprint,
  onNotifySuccess,
}) => {
  const [selectedFormat, setSelectedFormat] = useState<'pdf' | 'print' | 'markdown' | 'json'>('pdf');
  const [isExporting, setIsExporting] = useState(false);
  const [exportProgress, setExportProgress] = useState('');

  if (!isOpen) return null;

  const handleExport = async () => {
    if (isExporting) return;

    const slug = (project.name || 'stackmatch-blueprint')
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/(^-|-$)/g, '');

    if (selectedFormat === 'pdf') {
      setIsExporting(true);
      setExportProgress('Starting multi-page PDF generation...');
      try {
        await exportBlueprintToPdf('stackmatch-blueprint-doc', {
          filename: `${slug}-blueprint.pdf`,
          onProgress: (stage) => setExportProgress(stage),
        });
        if (onNotifySuccess) {
          onNotifySuccess(`Downloaded complete multi-page PDF: ${slug}-blueprint.pdf`);
        }
        onClose();
      } catch (err) {
        console.error('Failed to export PDF:', err);
        setExportProgress('Generation failed. Please try Print to PDF instead.');
      } finally {
        setIsExporting(false);
      }
      return;
    }

    if (selectedFormat === 'print') {
      onClose();
      setTimeout(() => {
        window.print();
        if (onNotifySuccess) {
          onNotifySuccess('Print dialog opened. Select "Save as PDF" to save the full blueprint.');
        }
      }, 300);
      return;
    }

    if (selectedFormat === 'markdown') {
      const mdContent = `# ${project.name} — StackMatch Engineering Blueprint
**Version:** ${blueprint.version || '1.0.0-PROPOSAL'}  
**Generated Date:** ${blueprint.generatedDate || new Date().toLocaleDateString()}  
**Tagline:** Plan smarter. Choose better. Build with confidence.

---

## 1. Executive Summary
- **Project Type:** ${project.summary?.projectType || 'Full-Stack Application'}
- **Estimated Complexity:** ${project.summary?.estimatedComplexity || 'Medium'}
- **Estimated Delivery Window:** ${project.summary?.estimatedTimeline || '3–6 months'}
- **Primary Users:** ${project.summary?.primaryUsers?.join(', ') || 'N/A'}
- **Target Audience:** ${project.summary?.targetAudience?.join(', ') || 'N/A'}

### Core Goals
${project.summary?.goals?.map((g) => `- ${g}`).join('\n') || '- Launch minimum viable product'}

---

## 2. Requirements & Agile Specifications
${requirements
  .map(
    (r, idx) => `### ${idx + 1}. ${r.title} [${r.type.toUpperCase()}]
- **Priority:** ${r.priority.toUpperCase()}
- **MVP Scope:** ${r.isMvpScope ? 'Yes (Core MVP)' : 'No (Phase 2+)'}
- **Category:** ${r.category || 'General'}
${r.userStory ? `- **User Story:** *"${r.userStory}"*` : ''}
- **Description:** ${r.description}
`
  )
  .join('\n')}

---

## 3. Recommended Technology Stack
${technologies
  .map(
    (t) => `### ${t.name} (${t.category})
- **Suitability Match Score:** ${t.matchScore}%
- **Tagline:** ${t.tagline}
- **Type / License:** ${t.keyInfo.type} / ${t.keyInfo.license}
- **Why Recommended:**
${t.whyRecommended.map((w) => `  - ${w}`).join('\n')}
- **Benefits:**
${t.benefits.map((b) => `  - ${b}`).join('\n')}
- **Considered Trade-offs:**
${t.tradeOffs.map((to) => `  - ${to}`).join('\n')}
- **Alternatives Evaluated:** ${t.alternatives.join(', ')}
- **Real-World Adoption:** ${t.realWorldUsage}
`
  )
  .join('\n')}

---

## 4. System Architecture Topography
${architectureNodes
  .map(
    (n) => `### [${n.layerTitle || n.layer}] ${n.name} (${n.technology})
- **Layer:** ${n.layerTitle || n.layer}
- **Description:** ${n.description}
- **Connects To:** ${n.connectsTo && n.connectsTo.length ? n.connectsTo.join(', ') : 'None'}
`
  )
  .join('\n')}

---

## 5. Development Roadmap Milestones
${roadmapPhases
  .map(
    (p) => `### Phase ${p.phaseNumber}: ${p.title} (${p.duration})
- **Status:** ${p.status}
- **Deliverables:**
${p.deliverables.map((d) => `  - [${d.completed ? 'x' : ' '}] ${d.title}${d.priority ? ` (${d.priority} priority)` : ''}`).join('\n')}
`
  )
  .join('\n')}

---
*Generated by StackMatch — AI-Powered Product Planning & Technology Intelligence.*
`;

      const blob = new Blob([mdContent], { type: 'text/markdown;charset=utf-8;' });
      const url = URL.createObjectURL(blob);
      const link = document.createElement('a');
      link.href = url;
      link.setAttribute('download', `${slug}-blueprint.md`);
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
      URL.revokeObjectURL(url);

      if (onNotifySuccess) {
        onNotifySuccess(`Downloaded ${slug}-blueprint.md`);
      }
      onClose();
      return;
    }

    if (selectedFormat === 'json') {
      const jsonSpec = {
        meta: {
          generator: 'StackMatch Platform v2.0',
          exportedAt: new Date().toISOString(),
          blueprintVersion: blueprint.version,
        },
        project,
        requirements,
        technologies,
        architecture: architectureNodes,
        roadmap: roadmapPhases,
        blueprint,
      };

      const blob = new Blob([JSON.stringify(jsonSpec, null, 2)], {
        type: 'application/json;charset=utf-8;',
      });
      const url = URL.createObjectURL(blob);
      const link = document.createElement('a');
      link.href = url;
      link.setAttribute('download', `${slug}-spec.json`);
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
      URL.revokeObjectURL(url);

      if (onNotifySuccess) {
        onNotifySuccess(`Downloaded ${slug}-spec.json`);
      }
      onClose();
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/50 backdrop-blur-xs animate-in fade-in duration-150">
      <div className="bg-white rounded-2xl border border-[#D1D5DB] shadow-2xl max-w-md w-full overflow-hidden flex flex-col">
        {/* Header */}
        <div className="px-6 py-4 border-b border-[#E5E7EB] flex items-center justify-between">
          <div className="flex items-center gap-2">
            <div className="w-8 h-8 rounded-lg bg-[#EFF6FF] text-[#2563EB] flex items-center justify-center">
              <Download className="w-4 h-4" />
            </div>
            <div>
              <h3 className="text-base font-bold text-[#111827]">Export Project Blueprint</h3>
              <p className="text-[11px] text-[#687280]">Choose your preferred export format</p>
            </div>
          </div>
          <button
            onClick={onClose}
            disabled={isExporting}
            className="text-[#9CA3AF] hover:text-[#111827] p-1.5 rounded-lg transition-subtle cursor-pointer disabled:opacity-50"
            aria-label="Close dialog"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        {/* Options */}
        <div className="p-6 space-y-3">
          <label
            onClick={() => !isExporting && setSelectedFormat('pdf')}
            className={`p-3.5 rounded-xl border flex items-start gap-3 cursor-pointer transition-all ${
              selectedFormat === 'pdf'
                ? 'border-[#2563EB] bg-[#EFF6FF]/40 shadow-2xs ring-1 ring-[#2563EB]/20'
                : 'border-[#E5E7EB] hover:border-[#D1D5DB]'
            }`}
          >
            <input
              type="radio"
              name="exportFormat"
              checked={selectedFormat === 'pdf'}
              onChange={() => setSelectedFormat('pdf')}
              disabled={isExporting}
              className="mt-1 text-[#2563EB] focus:ring-0"
            />
            <div className="flex-1">
              <div className="flex items-center gap-2">
                <Download className="w-4 h-4 text-[#2563EB]" />
                <span className="text-xs font-bold text-[#111827]">Multi-Page PDF Download (.pdf)</span>
                <Badge variant="highlight" size="sm">
                  Recommended
                </Badge>
              </div>
              <p className="text-[11px] text-[#687280] mt-0.5">
                Complete multi-page PDF with all sections, technologies, logos, and architecture included.
              </p>
            </div>
          </label>

          <label
            onClick={() => !isExporting && setSelectedFormat('print')}
            className={`p-3.5 rounded-xl border flex items-start gap-3 cursor-pointer transition-all ${
              selectedFormat === 'print'
                ? 'border-[#111827] bg-[#F9FAFB] shadow-2xs'
                : 'border-[#E5E7EB] hover:border-[#D1D5DB]'
            }`}
          >
            <input
              type="radio"
              name="exportFormat"
              checked={selectedFormat === 'print'}
              onChange={() => setSelectedFormat('print')}
              disabled={isExporting}
              className="mt-1 text-[#111827] focus:ring-0"
            />
            <div className="flex-1">
              <div className="flex items-center gap-2">
                <Printer className="w-4 h-4 text-[#111827]" />
                <span className="text-xs font-bold text-[#111827]">Print to PDF (Vector Print)</span>
              </div>
              <p className="text-[11px] text-[#687280] mt-0.5">
                Native browser print dialog with full CSS pagination and selectable vector typography.
              </p>
            </div>
          </label>

          <label
            onClick={() => !isExporting && setSelectedFormat('markdown')}
            className={`p-3.5 rounded-xl border flex items-start gap-3 cursor-pointer transition-all ${
              selectedFormat === 'markdown'
                ? 'border-[#111827] bg-[#F9FAFB] shadow-2xs'
                : 'border-[#E5E7EB] hover:border-[#D1D5DB]'
            }`}
          >
            <input
              type="radio"
              name="exportFormat"
              checked={selectedFormat === 'markdown'}
              onChange={() => setSelectedFormat('markdown')}
              disabled={isExporting}
              className="mt-1 text-[#111827] focus:ring-0"
            />
            <div className="flex-1">
              <div className="flex items-center gap-2">
                <FileText className="w-4 h-4 text-[#16A34A]" />
                <span className="text-xs font-bold text-[#111827]">Markdown Document (.md)</span>
              </div>
              <p className="text-[11px] text-[#687280] mt-0.5">
                Complete engineering specification compatible with GitHub, Notion, and Obsidian.
              </p>
            </div>
          </label>

          <label
            onClick={() => !isExporting && setSelectedFormat('json')}
            className={`p-3.5 rounded-xl border flex items-start gap-3 cursor-pointer transition-all ${
              selectedFormat === 'json'
                ? 'border-[#111827] bg-[#F9FAFB] shadow-2xs'
                : 'border-[#E5E7EB] hover:border-[#D1D5DB]'
            }`}
          >
            <input
              type="radio"
              name="exportFormat"
              checked={selectedFormat === 'json'}
              onChange={() => setSelectedFormat('json')}
              disabled={isExporting}
              className="mt-1 text-[#111827] focus:ring-0"
            />
            <div className="flex-1">
              <div className="flex items-center gap-2">
                <Code2 className="w-4 h-4 text-[#2563EB]" />
                <span className="text-xs font-bold text-[#111827]">JSON Specification (.json)</span>
              </div>
              <p className="text-[11px] text-[#687280] mt-0.5">
                Structured schema of all requirements, stack scores, and roadmap deliverables.
              </p>
            </div>
          </label>

          {isExporting && exportProgress && (
            <div className="p-3 rounded-lg bg-blue-50 border border-blue-200 flex items-center gap-2.5 text-xs text-blue-700 animate-pulse">
              <Loader2 className="w-4 h-4 animate-spin shrink-0 text-blue-600" />
              <span>{exportProgress}</span>
            </div>
          )}
        </div>

        {/* Footer */}
        <div className="px-6 py-4 border-t border-[#E5E7EB] flex items-center justify-between">
          <Button variant="ghost" size="sm" onClick={onClose} disabled={isExporting}>
            Cancel
          </Button>
          <Button
            variant="accent"
            size="sm"
            onClick={handleExport}
            disabled={isExporting}
            leftIcon={
              isExporting ? (
                <Loader2 className="w-3.5 h-3.5 animate-spin" />
              ) : (
                <Download className="w-3.5 h-3.5" />
              )
            }
          >
            {isExporting
              ? 'Generating PDF...'
              : selectedFormat === 'print'
              ? 'Open Print Dialog'
              : 'Download File'}
          </Button>
        </div>
      </div>
    </div>
  );
};
